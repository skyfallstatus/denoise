"""Embed core/shaders/*.metal into a C++ source file.

usage: embed_shaders.py OUT.cpp SHADER_DIR

There is no offline `metal` compiler on the build machine, so shaders ship as
source strings and are compiled at run time (newLibraryWithSource).

Rules for files in core/shaders (the contract for stage authors):

* Every `*.metal` file is one *unit*, compiled lazily as its own MTLLibrary,
  EXCEPT header files: `common.metal` and any file whose name ends in
  `_inc.metal`. Headers are never compiled alone.
* `common.metal` is put in front of every unit automatically.
* A unit or header may pull in a header with a line of exactly this form:
      #include "temporal_inc.metal"
  It is resolved here, textually, at build time, once per unit (a second
  include of the same file in one unit is dropped). Only headers can be
  included.
* Kernel entry points (`kernel void NAME(`) must have globally unique names,
  conventionally prefixed with the stage name. The runtime finds the unit from
  the kernel name alone: Context::pipeline("temporal_merge").
* Math mode is chosen per unit with a comment line anywhere in the unit file:
      // od: math=safe | relaxed | fast
  Default is `safe` (IEEE: NaN/Inf respected, no reassociation), because the
  strength-0 identity guarantee and NaN scrubbing rely on it. Opt in to
  `relaxed` or `fast` for heavy filters after checking the output.
* `#line` directives are emitted so a compile error names the original file
  and line.
"""
import os
import re
import sys

INCLUDE_RE = re.compile(r'^\s*#include\s+"([^"]+)"\s*$')
KERNEL_RE = re.compile(r'^\s*kernel\s+void\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(', re.M)
MATH_RE = re.compile(r'^\s*//\s*od:\s*math\s*=\s*(safe|relaxed|fast)\s*$', re.M)
MATH = {"safe": 0, "relaxed": 1, "fast": 2}


def is_header(name):
    return name == "common.metal" or name.endswith("_inc.metal")


def expand(shader_dir, name, seen, out, stack):
    if name in seen:
        return
    seen.add(name)
    path = os.path.join(shader_dir, name)
    if not os.path.isfile(path):
        sys.exit("embed_shaders: %s includes missing file %s" % (stack[-1] if stack else "?", name))
    out.append('#line 1 "%s"\n' % name)
    with open(path, "r", encoding="utf-8") as f:
        lines = f.read().split("\n")
    for i, line in enumerate(lines):
        m = INCLUDE_RE.match(line)
        if m:
            inc = m.group(1)
            if not is_header(inc):
                sys.exit("embed_shaders: %s:%d: only common.metal and *_inc.metal can be included (got %s)"
                         % (name, i + 1, inc))
            expand(shader_dir, inc, seen, out, stack + [name])
            out.append('#line %d "%s"\n' % (i + 2, name))
        else:
            out.append(line + "\n")


def c_string(text):
    # Adjacent ordinary string literals, one per line: no raw-string delimiter
    # or length-limit concerns.
    parts = []
    for line in text.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        parts.append('  "%s\\n"' % esc)
    return "\n".join(parts)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    out_path, shader_dir = sys.argv[1], sys.argv[2]
    names = sorted(n for n in os.listdir(shader_dir) if n.endswith(".metal"))
    units = [n for n in names if not is_header(n)]
    has_common = "common.metal" in names

    kernels = {}
    chunks = []
    for ui, name in enumerate(units):
        out, seen = [], set()
        if has_common:
            expand(shader_dir, "common.metal", seen, out, [name])
        expand(shader_dir, name, seen, out, [])
        text = "".join(out)
        with open(os.path.join(shader_dir, name), "r", encoding="utf-8") as f:
            own = f.read()
        m = MATH_RE.search(own)
        math = MATH[m.group(1)] if m else 0
        for k in KERNEL_RE.findall(text):
            if k in kernels and kernels[k] != ui:
                sys.exit("embed_shaders: kernel '%s' defined in both %s and %s; kernel names must be unique"
                         % (k, units[kernels[k]], name))
            kernels[k] = ui
        chunks.append((name, math, text))

    with open(out_path + ".tmp", "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/embed_shaders.py. Do not edit.\n")
        f.write('#include "shaders.h"\n\nnamespace od {\n\n')
        for ui, (name, math, text) in enumerate(chunks):
            f.write("static const char kSrc%d[] =\n%s;\n\n" % (ui, c_string(text)))
        f.write("const ShaderUnit kShaderUnits[] = {\n")
        for ui, (name, math, text) in enumerate(chunks):
            f.write('  {"%s", kSrc%d, %d},\n' % (name, ui, math))
        f.write("  {nullptr, nullptr, 0}\n};\n")
        f.write("const int kShaderUnitCount = %d;\n\n" % len(chunks))
        f.write("const ShaderKernel kShaderKernels[] = {\n")
        for k in sorted(kernels):
            f.write('  {"%s", %d},\n' % (k, kernels[k]))
        f.write("  {nullptr, 0}\n};\n")
        f.write("const int kShaderKernelCount = %d;\n\n}  // namespace od\n" % len(kernels))
    os.replace(out_path + ".tmp", out_path)


if __name__ == "__main__":
    main()
